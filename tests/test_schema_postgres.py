"""
PostgreSQL integration tests for migrations and schema files.

Skipped unless SCRIBE_TEST_POSTGRES holds connection settings as JSON, e.g.:

    SCRIBE_TEST_POSTGRES='{"host": "localhost", "port": 5432, "user": "scribe", "database": "scribe_test"}'

WARNING: the tests drop and recreate the public and reporting schemas in that
database. The database name must contain "test" as a safeguard.
"""

import glob
import json
import os

import pytest
from click.testing import CliRunner

from scribe.cli import cli

SETTINGS = os.environ.get('SCRIBE_TEST_POSTGRES')

pytestmark = pytest.mark.skipif(not SETTINGS, reason="Set SCRIBE_TEST_POSTGRES to run PostgreSQL tests")

SEED = """
CREATE TABLE customers (
    id SERIAL PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    name TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT true,
    credit_limit NUMERIC(12,2) DEFAULT 0,
    created_at TIMESTAMP DEFAULT now()
);
CREATE TABLE products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(32) NOT NULL,
    region CHAR(2) NOT NULL DEFAULT 'US',
    tags TEXT[],
    UNIQUE (sku, region)
);
CREATE TABLE orders (
    id BIGSERIAL PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customers(id),
    status VARCHAR(20) DEFAULT 'open',
    placed_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_orders_status ON orders (status);
CREATE UNIQUE INDEX idx_customers_lower_email ON customers (LOWER(email));
CREATE TABLE reporting.daily_sales (
    day DATE PRIMARY KEY,
    customer_id INTEGER REFERENCES public.customers(id),
    amount NUMERIC(14,2) NOT NULL
);
CREATE VIEW open_orders AS SELECT id, status FROM orders WHERE status = 'open';
INSERT INTO customers (email, name) VALUES ('ada@example.com', 'Ada'), ('grace@example.com', 'Grace');
INSERT INTO orders (customer_id) VALUES (1), (2);
"""


@pytest.fixture
def project(tmp_path):
    from scribe.database import create_adapter

    settings = json.loads(SETTINGS)
    assert 'test' in settings['database'], "SCRIBE_TEST_POSTGRES database name must contain 'test'"
    block = {'type': 'postgresql', **settings, 'migrations': 'migrations', 'auto_migrate': False}

    db = create_adapter(block)
    db.execute("DROP SCHEMA IF EXISTS public CASCADE")
    db.execute("DROP SCHEMA IF EXISTS reporting CASCADE")
    db.execute("CREATE SCHEMA public")
    db.execute("CREATE SCHEMA reporting")
    for statement in SEED.split(';'):
        if statement.strip():
            db.execute(statement)
    db.commit()

    with open(tmp_path / 'scribe.json', 'w') as f:
        json.dump({'databases': {'default': block}}, f)
    os.makedirs(tmp_path / 'migrations')
    yield tmp_path, db
    db.close()


def run(*args):
    result = CliRunner().invoke(cli, list(args))
    return result


def schema_text(path):
    return (path / 'schemas' / 'schema_default.py').read_text()


def set_schema(path, text):
    (path / 'schemas' / 'schema_default.py').write_text(text)


def test_introspection(project):
    path, db = project

    assert db.get_tables() == ['public.customers', 'public.orders', 'public.products', 'reporting.daily_sales']
    assert 'public.open_orders' in db.get_tables(include_views=True)

    columns = {c.name: c for c in db.get_columns('customers')}
    assert columns['id'].autoincrement and columns['id'].default is None
    assert columns['email'].type == 'character varying(255)'
    assert columns['credit_limit'].type == 'numeric(12,2)'
    assert {c.name: c.autoincrement for c in db.get_columns('products')}['id']

    indexes = {i.name: i for i in db.get_indexes('products')}
    assert indexes['products_sku_region_key'].origin == 'unique'
    assert indexes['products_sku_region_key'].columns == ['sku', 'region']
    expression = {i.name: i for i in db.get_indexes('customers')}['idx_customers_lower_email']
    assert expression.columns == [None]

    [fk] = db.get_foreign_keys('reporting.daily_sales')
    assert (fk.columns, fk.ref_table, fk.ref_columns) == (['customer_id'], 'public.customers', ['id'])


def test_pull_round_trip(project):
    path, _ = project

    result = run('schema', 'pull', '--path', str(path))
    assert result.exit_code == 0, result.output
    assert 'open_orders' not in schema_text(path)

    set_schema(path, schema_text(path).replace('    managed=False,', '    managed=True,'))
    result = run('schema', 'diff', '--path', str(path))
    assert "No differences in 4 managed table(s)" in result.output, result.output


def test_generate_migrate_cycle(project):
    path, db = project
    assert run('schema', 'pull', '--path', str(path)).exit_code == 0
    text = schema_text(path).replace('    managed=False,', '    managed=True,')
    text = text.replace('Column("status", "character varying(20)", default="open"),',
                        'Column("status", "character varying(20)", nullable=False, default="open"),')
    text += '''
Table("user_roles",
    Column("user_id", "integer", ForeignKey("user.id"), primary_key=True),
    Column("role", "varchar(20)", primary_key=True),
)
Table("user",
    Column("id", "integer", primary_key=True, autoincrement=True),
    Column("login", "varchar(50)", nullable=False, unique=True),
    Column("created", "timestamptz", default=sql("now()")),
)
Table("reporting.weekly_sales", Column("week", "date", primary_key=True))
raw_sql("idx_customers_lower_name", "CREATE INDEX IF NOT EXISTS idx_customers_lower_name ON customers (LOWER(name))")
'''
    set_schema(path, text)

    result = run('schema', 'generate', '--path', str(path))
    assert result.exit_code == 0, result.output
    assert "4 statement(s) will run, 1 commented out" in result.output
    result = run('db', 'migrate', '--path', str(path))
    assert result.exit_code == 0, result.output

    # Only the review item is left: make status NOT NULL
    result = run('schema', 'diff', '--path', str(path))
    assert "status: make NOT NULL" in result.output and "0 additive, 1 need review" in result.output

    result = run('schema', 'generate', '--force', '--name', 'review', '--path', str(path))
    assert result.exit_code == 0, result.output
    [review] = glob.glob(str(path / 'migrations' / '002_review.sql'))
    with open(review) as f:
        sql = f.read().replace('-- ALTER TABLE orders ALTER COLUMN status SET NOT NULL;',
                               'ALTER TABLE orders ALTER COLUMN status SET NOT NULL;')
    with open(review, 'w') as f:
        f.write(sql)
    result = run('db', 'migrate', '--path', str(path))
    assert result.exit_code == 0, result.output

    assert "No differences in 7 managed table(s)" in run('schema', 'diff', '--path', str(path)).output
    assert "nothing to generate" in run('schema', 'generate', '--path', str(path)).output
    assert len(db.query('SELECT * FROM orders')) == 2


def test_failed_migration_rolls_back(project):
    path, db = project
    (path / 'migrations' / '001_bad.sql').write_text("CREATE TABLE tags (id SERIAL PRIMARY KEY);\nCREATE TABLE broken (;\n")

    result = run('db', 'migrate', '--path', str(path))

    assert result.exit_code == 1
    db.rollback()
    assert not db.has_table('tags')
    assert db.query("SELECT COUNT(*) AS n FROM _migrations")[0]['n'] == 0


def test_apply(project):
    path, db = project
    config = json.loads((path / 'scribe.json').read_text())
    assert run('schema', 'pull', '--path', str(path)).exit_code == 0
    set_schema(path, schema_text(path).replace('    managed=False,', '    managed=True,') + '''
Table("audit_events",
    Column("id", "bigint", primary_key=True, autoincrement=True),
    Column("customer_id", "integer", ForeignKey("customers.id")),
)
Table("broken", Column("id", "integer", ForeignKey("nowhere.id")))
''')

    # auto_migrate is false in the fixture, so apply refuses
    result = run('schema', 'apply', '--database', 'default', '--path', str(path))
    assert result.exit_code != 0 and "auto_migrate off" in result.output

    config['databases']['default']['auto_migrate'] = True
    (path / 'scribe.json').write_text(json.dumps(config))

    # One statement fails, so the whole migration rolls back and its file is removed
    result = run('schema', 'apply', '--path', str(path))
    assert result.exit_code != 0 and "rolled back; the file was removed" in result.output
    db.rollback()
    assert not db.has_table('audit_events')
    assert glob.glob(str(path / 'migrations' / '*.sql')) == []

    set_schema(path, schema_text(path).replace('Table("broken", Column("id", "integer", ForeignKey("nowhere.id")))\n', ''))
    result = run('schema', 'apply', '--path', str(path))
    assert result.exit_code == 0, result.output
    assert db.has_table('audit_events')
    assert "No differences in 5 managed table(s)" in run('schema', 'diff', '--path', str(path)).output


def test_scoped_pull_across_schemas(project):
    path, db = project
    db.execute("CREATE TABLE reporting.daily_sales_backup (LIKE reporting.daily_sales)")
    db.execute("CREATE TABLE orders_backup (LIKE orders)")
    db.commit()

    result = run('schema', 'pull', '--include', 'orders*', '--include', 'reporting.*',
                 '--exclude', '*_backup', '--path', str(path))

    assert result.exit_code == 0, result.output
    assert "(2 of 6 tables in scope)" in result.output
    text = schema_text(path)
    assert 'Table("orders",' in text and 'Table("reporting.daily_sales",' in text
    assert '_backup' not in text.split('scope(')[1].split(')')[1]

    result = run('schema', 'status', '--path', str(path))
    assert "scope:       2 of 6 database table(s)" in result.output
