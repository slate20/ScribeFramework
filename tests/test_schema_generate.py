def test_review_only_changes_need_force(tmp_path):
    path, _ = make_project(tmp_path, 'Table("t", Column("id", "INTEGER"))\n',
                           setup=["CREATE TABLE t (id INTEGER, legacy TEXT)"])

    result = run('schema', 'generate', '--path', path)
    assert "all 1 change(s) need review" in result.output
    assert migration_files(tmp_path) == []

    result = run('schema', 'generate', '--force', '--path', path)
    assert result.exit_code == 0, result.output
    text = open(migration_files(tmp_path)[0]).read()
    assert "-- REVIEW: destructive — t.legacy" in text
    assert "-- ALTER TABLE t DROP COLUMN legacy;" in text


def test_sqlite_rebuild_preserves_data_when_uncommented(tmp_path):
    path, db = make_project(tmp_path, """
Table("tasks",
    Column("id", "INTEGER", primary_key=True, autoincrement=True),
    Column("title", "VARCHAR(200)", nullable=False),
    Column("done", "BOOLEAN", default=False),
    Column("priority", "INTEGER", default=0),
)
""", setup=["CREATE TABLE tasks (id INTEGER PRIMARY KEY AUTOINCREMENT, title TEXT, done BOOLEAN DEFAULT 1)",
            "CREATE INDEX idx_tasks_title ON tasks (title)",
            "INSERT INTO tasks (title, done) VALUES ('one', 1), ('two', 0)"])

    result = run('schema', 'generate', '--path', path)
    assert result.exit_code == 0, result.output
    [file] = migration_files(tmp_path)
    text = open(file).read()
    assert "ALTER TABLE tasks ADD COLUMN priority INTEGER DEFAULT 0;" in text
    assert "-- REVIEW: SQLite can't make these changes to tasks in place:" in text
    # The rebuild copies the column added by the live statement above it
    assert ("-- INSERT INTO tasks__scribe_new (id, title, done, priority) "
            "SELECT id, title, done, priority FROM tasks;") in text

    uncomment(file, lambda line: line.startswith(('CREATE', 'INSERT', 'DROP', 'ALTER', '    ', ');')))
    result = run('db', 'migrate', '--path', path)
    assert result.exit_code == 0, result.output

    rows = [r.to_dict() for r in db.query("SELECT id, title, done, priority FROM tasks ORDER BY id")]
    assert rows == [{'id': 1, 'title': 'one', 'done': 1, 'priority': 0},
                    {'id': 2, 'title': 'two', 'done': 0, 'priority': 0}]
    assert "No differences" in run('schema', 'diff', '--path', path).output


def test_rename_suggestion_runs(tmp_path):
    path, db = make_project(tmp_path, """
Table("users", Column("id", "INTEGER", primary_key=True), Column("pw_hash", "TEXT"))
""", setup=["CREATE TABLE users (id INTEGER PRIMARY KEY, password_hash TEXT)",
            "INSERT INTO users (password_hash) VALUES ('secret')"])

    result = run('schema', 'generate', '--force', '--path', path)
    assert result.exit_code == 0, result.output
    [file] = migration_files(tmp_path)
    text = open(file).read()
    assert "-- ALTER TABLE users RENAME COLUMN password_hash TO pw_hash;" in text
    assert "If it isn't a rename, uncomment these two instead:" in text

    uncomment(file, lambda line: line.startswith('ALTER TABLE users RENAME'))
    assert run('db', 'migrate', '--path', path).exit_code == 0
    assert db.query("SELECT pw_hash FROM users")[0]['pw_hash'] == 'secret'
    assert "No differences" in run('schema', 'diff', '--path', path).output


def test_sqlite_non_constant_default_needs_review(tmp_path):
    _, db = make_project(tmp_path, "", setup=["CREATE TABLE t (id INTEGER)"])
    definition = load_schema(str(tmp_path / 'schemas' / 'schema_default.py'))
    definition.add('table', Table("t", Column("id", "INTEGER"),
                                  Column("at", "TIMESTAMP", default=sql("CURRENT_TIMESTAMP"))))
    [change] = diff_schema(definition, read_live_schema(db), 'sqlite').changes
    assert not change.additive
    assert "non-constant default" in change.description
    # PostgreSQL can add it in place
    [change] = diff_schema(definition, read_live_schema(db), 'postgresql').changes
    assert change.additive


def test_raw_sql_generated_once(tmp_path):
    path, _ = make_project(tmp_path, 'raw_sql("v", "CREATE VIEW IF NOT EXISTS v AS SELECT 1 AS one")\n')

    assert run('schema', 'generate', '--path', path).exit_code == 0
    assert run('db', 'migrate', '--path', path).exit_code == 0
    assert "nothing to generate" in run('schema', 'generate', '--path', path).output

    write(tmp_path / 'schemas' / 'schema_default.py', HEADER)
    result = run('schema', 'generate', '--force', '--path', path)
    assert result.exit_code == 0, result.output
    assert "-- raw_sql: v removed" in open(migration_files(tmp_path)[-1]).read()
    assert run('db', 'migrate', '--path', path).exit_code == 0
    assert "nothing to generate" in run('schema', 'generate', '--path', path).output


