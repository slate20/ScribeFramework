"""
Tests for `scribe schema generate`: SQL rendering, raw_sql tracking, and the
generate -> migrate -> diff cycle on SQLite.
"""

import glob
import json
import os
import re

import pytest
from click.testing import CliRunner

from scribe.cli import cli, _report_schema_changes
from scribe.database import create_adapter, DatabaseManager
from scribe.schema import Table, Column, Index, ForeignKey, sql
from scribe.schema.diff import diff_schema
from scribe.schema.generate import (
    quote, raw_sql_changes, raw_sql_hash, read_raw_sql_state, render_add_column, render_column,
    render_create_table, _drop_index,
)
from scribe.schema.introspect import read_live_schema
from scribe.schema.loader import load_schema

HEADER = "from scribe.schema import Table, Column, Index, ForeignKey, sql, raw_sql, unmanaged\n\n"


def write(path, content):
    os.makedirs(os.path.dirname(str(path)), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(content)


def make_project(tmp_path, body, block=None, setup=()):
    block = block or {'type': 'sqlite', 'database': str(tmp_path / 'app.db'), 'auto_migrate': False}
    write(tmp_path / 'scribe.json', json.dumps({'databases': {'default': block}}))
    write(tmp_path / 'schemas' / 'schema_default.py', HEADER + body)
    os.makedirs(tmp_path / 'migrations', exist_ok=True)
    db = create_adapter({'type': 'sqlite', 'database': str(tmp_path / 'app.db')})
    for statement in setup:
        db.execute(statement)
    return str(tmp_path), db


def run(*args):
    return CliRunner().invoke(cli, list(args))


def migration_files(tmp_path):
    return sorted(glob.glob(str(tmp_path / 'migrations' / '*.sql')))


def uncomment(path, predicate):
    """Uncomment '-- ' lines whose text matches predicate, as a person reviewing the file would."""
    with open(path) as f:
        lines = f.read().splitlines()
    out = [line[3:] if line.startswith('-- ') and predicate(line[3:]) else line for line in lines]
    with open(path, 'w') as f:
        f.write('\n'.join(out) + '\n')


# === Rendering ===

def test_quote_only_when_needed():
    assert quote('users', 'postgresql') == 'users'
    assert quote('user', 'postgresql') == '"user"'
    assert quote('order', 'mssql') == '[order]'
    assert quote('reporting.order', 'postgresql') == 'reporting."order"'
    assert quote('my table', 'sqlite') == '"my table"'


def test_render_autoincrement_per_dialect():
    column = Column("id", "integer", primary_key=True, autoincrement=True)
    assert render_column(column, 'postgresql') == 'id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
    assert render_column(column, 'mssql') == 'id integer IDENTITY(1,1) PRIMARY KEY'
    assert render_column(Column("id", "INTEGER", primary_key=True, autoincrement=True), 'sqlite') == \
        'id INTEGER PRIMARY KEY AUTOINCREMENT'
    # SERIAL already implies the sequence
    assert render_column(Column("id", "SERIAL", primary_key=True), 'postgresql') == 'id SERIAL PRIMARY KEY'


def test_render_defaults():
    assert render_column(Column("a", "BOOLEAN", default=True), 'postgresql') == 'a BOOLEAN DEFAULT true'
    assert render_column(Column("a", "BIT", default=True), 'mssql') == 'a BIT DEFAULT 1'
    assert render_column(Column("a", "TEXT", default="it's"), 'sqlite') == "a TEXT DEFAULT 'it''s'"
    assert render_column(Column("a", "TIMESTAMP", default=sql("CURRENT_TIMESTAMP")), 'sqlite') == \
        'a TIMESTAMP DEFAULT CURRENT_TIMESTAMP'
    # SQLite needs parentheses around other expressions
    assert render_column(Column("a", "TEXT", default=sql("lower('X')")), 'sqlite') == \
        "a TEXT DEFAULT (lower('X'))"
    assert render_column(Column("a", "TEXT", default=sql("lower('X')")), 'postgresql') == \
        "a TEXT DEFAULT lower('X')"


def test_render_dialect_specific_statements():
    column = Column("note", "TEXT")
    assert render_add_column('t', column, 'mssql') == 'ALTER TABLE t ADD note TEXT;'
    assert render_add_column('t', column, 'postgresql') == 'ALTER TABLE t ADD COLUMN note TEXT;'
    assert _drop_index('idx', 't', 'mssql') == 'DROP INDEX idx ON t;'
    assert _drop_index('idx', 'reporting.t', 'postgresql') == 'DROP INDEX reporting.idx;'


def test_mssql_unique_on_nullable_column_ignores_nulls():
    from scribe.schema.diff import Change
    from scribe.schema.generate import _render_additive

    nullable = Change('add_unique', 't', 'add UNIQUE', True, column='email', declared=Column("email", "nvarchar(255)"))
    required = Change('add_unique', 't', 'add UNIQUE', True, column='email',
                      declared=Column("email", "nvarchar(255)", nullable=False))
    assert _render_additive(nullable, 'mssql') == "CREATE UNIQUE INDEX uq_t_email ON t (email) WHERE email IS NOT NULL;"
    assert _render_additive(required, 'mssql') == "CREATE UNIQUE INDEX uq_t_email ON t (email);"
    assert _render_additive(nullable, 'postgresql') == "CREATE UNIQUE INDEX uq_t_email ON t (email);"


def test_render_composite_primary_key():
    table = Table("pairs", Column("a", "INTEGER", primary_key=True), Column("b", "INTEGER", primary_key=True))
    assert render_create_table(table, 'sqlite') == (
        "CREATE TABLE pairs (\n    a INTEGER NOT NULL,\n    b INTEGER NOT NULL,\n    PRIMARY KEY (a, b)\n);"
    )


# === raw_sql tracking ===

def test_raw_sql_state_from_markers(tmp_path):
    write(tmp_path / '001_a.sql', "-- raw_sql: v1 sha256:aaaa\n-- raw_sql: v2 sha256:bbbb\n")
    write(tmp_path / '002_b.sql', "-- raw_sql: v1 sha256:cccc\n-- raw_sql: v2 removed\n")
    assert read_raw_sql_state(str(tmp_path)) == {'v1': 'cccc', 'v2': None}


def test_raw_sql_changes(tmp_path):
    path, _ = make_project(tmp_path, 'raw_sql("same", "SELECT 1")\nraw_sql("edited", "SELECT 2")\n'
                                     'raw_sql("fresh", "SELECT 3")\n')
    write(tmp_path / 'migrations' / '001_x.sql',
          f"-- raw_sql: same sha256:{raw_sql_hash('SELECT 1')}\n"
          f"-- raw_sql: edited sha256:{raw_sql_hash('SELECT 0')}\n"
          f"-- raw_sql: gone sha256:{raw_sql_hash('SELECT 9')}\n")
    definition = load_schema(str(tmp_path / 'schemas' / 'schema_default.py'))

    changes = {c.name: c.status for c in raw_sql_changes(definition, str(tmp_path / 'migrations'))}
    assert changes == {'edited': 'changed', 'fresh': 'new', 'gone': 'removed'}


def test_raw_sql_hash_ignores_trailing_whitespace():
    assert raw_sql_hash("SELECT 1;  \n") == raw_sql_hash("\nSELECT 1;")


# === generate -> migrate -> diff ===

def test_generate_apply_and_rediff(tmp_path):
    path, db = make_project(tmp_path, """
Table("users",
    Column("id", "INTEGER", primary_key=True, autoincrement=True),
    Column("email", "TEXT", nullable=False),
    Column("nickname", "TEXT"),
)
Table("order_items",
    Column("id", "INTEGER", primary_key=True),
    Column("order_id", "INTEGER", ForeignKey("order.id")),
)
Table("order",
    Column("id", "INTEGER", primary_key=True, autoincrement=True),
    Column("user_id", "INTEGER", ForeignKey("users.id"), nullable=False),
    Column("status", "TEXT", default="open"),
)
Index("idx_order_status", "order", ["status"])
raw_sql("v_open", "CREATE VIEW IF NOT EXISTS v_open AS SELECT * FROM \\"order\\" WHERE status = 'open'")
""", setup=["CREATE TABLE users (id INTEGER PRIMARY KEY AUTOINCREMENT, email TEXT NOT NULL)",
            "INSERT INTO users (email) VALUES ('a@example.com')"])

    result = run('schema', 'generate', '--path', path)
    assert result.exit_code == 0, result.output
    assert "5 statement(s) will run, 0 commented out" in result.output

    [file] = migration_files(tmp_path)
    assert os.path.basename(file) == '001_schema_users_order_items_order.sql'
    text = open(file).read()
    # Referenced tables are created first, and reserved names are quoted
    assert text.index('CREATE TABLE "order"') < text.index('CREATE TABLE order_items')
    assert 'REFERENCES "order"(id)' in text

    result = run('db', 'migrate', '--path', path)
    assert result.exit_code == 0, result.output
    assert db.query("SELECT email, nickname FROM users")[0].to_dict() == {'email': 'a@example.com', 'nickname': None}
    assert db.query("SELECT name FROM sqlite_master WHERE type = 'view'")[0]['name'] == 'v_open'

    result = run('schema', 'diff', '--path', path)
    assert "No differences in 3 managed table(s)" in result.output
    result = run('schema', 'generate', '--path', path)
    assert "nothing to generate" in result.output


def test_generate_refuses_with_pending_migrations(tmp_path):
    path, _ = make_project(tmp_path, 'Table("t", Column("id", "INTEGER"))\n')
    write(tmp_path / 'migrations' / '001_manual.sql', "CREATE TABLE other (id INTEGER);")

    result = run('schema', 'generate', '--path', path)

    assert result.exit_code != 0
    assert "1 pending migration(s) (001_manual.sql)" in result.output
    assert migration_files(tmp_path) == [str(tmp_path / 'migrations' / '001_manual.sql')]


