"""
Rendering a schema diff as a .sql migration (`scribe schema generate`).

Additive changes become live SQL. Everything else is written as
commented-out SQL under a "-- REVIEW" heading, so running the migration
never drops data or rewrites a column; the author uncomments what they
want. On SQLite, changes that can't be made in place are gathered into
one commented table-rebuild sequence per table.

raw_sql() blocks are tracked by hash through marker comments in the
generated files themselves ("-- raw_sql: name sha256:..."), so no extra
table is needed and a block isn't emitted twice.
"""

import datetime
import glob
import hashlib
import os
import re
from dataclasses import dataclass, field
from typing import Dict, List, Optional

from scribe.schema.diff import Change, SchemaDiff
from scribe.schema.dsl import Column, Index, RawSQL, SchemaDefinition, SqlExpression, Table
from scribe.schema.introspect import LiveTable
from scribe.schema.normalize import declared_default_sql, normalize_type

# Common words that are reserved in at least one supported database
_RESERVED = {
    'all', 'and', 'as', 'asc', 'between', 'by', 'case', 'check', 'column', 'constraint', 'create',
    'current_date', 'current_time', 'current_timestamp', 'current_user', 'default', 'delete', 'desc',
    'distinct', 'drop', 'else', 'end', 'exists', 'foreign', 'from', 'grant', 'group', 'having', 'in',
    'index', 'insert', 'into', 'is', 'join', 'key', 'like', 'limit', 'not', 'null', 'offset', 'on',
    'or', 'order', 'primary', 'references', 'select', 'session_user', 'set', 'table', 'then', 'to',
    'union', 'unique', 'update', 'user', 'using', 'values', 'when', 'where', 'with',
}

# Changes SQLite can only make by rebuilding the table
_SQLITE_REBUILD_KINDS = {
    'alter_column_type', 'alter_column_nullable', 'alter_column_default', 'alter_column_autoincrement',
    'alter_primary_key', 'add_foreign_key', 'drop_foreign_key',
}

_RAW_MARKER = re.compile(r'^-- raw_sql: (\S+) (?:sha256:([0-9a-f]+)|(removed))\s*$', re.MULTILINE)


# === Identifiers ===

def quote(name: str, dialect: str) -> str:
    """Quote an identifier (or 'schema.table') only where needed."""
    return '.'.join(_quote_part(part, dialect) for part in name.split('.'))


def _quote_part(part: str, dialect: str) -> str:
    if re.match(r'^[A-Za-z_][A-Za-z0-9_]*$', part) and part.lower() not in _RESERVED:
        return part
    if dialect == 'mssql':
        return '[' + part.replace(']', ']]') + ']'
    return '"' + part.replace('"', '""') + '"'


def _bare(name: str) -> str:
    return name.rpartition('.')[2]


def _columns(names: List[str], dialect: str) -> str:
    return ', '.join(quote(name, dialect) for name in names)


# === Definitions ===

def _default_clause(column: Column, dialect: str) -> Optional[str]:
    text = declared_default_sql(column.default, dialect)
    if text is None:
        return None
    # SQLite needs parentheses around expressions other than the CURRENT_* keywords
    if dialect == 'sqlite' and isinstance(column.default, SqlExpression):
        if text.upper() not in ('CURRENT_TIMESTAMP', 'CURRENT_DATE', 'CURRENT_TIME') and not text.startswith('('):
            text = f"({text})"
    return f"DEFAULT {text}"


def render_column(column: Column, dialect: str, inline_primary_key: bool = True) -> str:
    """Column definition as used in CREATE TABLE and ADD COLUMN."""
    parts = [quote(column.name, dialect), column.type]

    serial_type = normalize_type(column.type, dialect)[1]
    if column.autoincrement and not serial_type:
        if dialect == 'postgresql':
            parts.append('GENERATED BY DEFAULT AS IDENTITY')
        elif dialect == 'mssql':
            parts.append('IDENTITY(1,1)')

    if column.primary_key and inline_primary_key:
        parts.append('PRIMARY KEY')
        if dialect == 'sqlite' and column.autoincrement:
            parts.append('AUTOINCREMENT')
    if not column.nullable and not (column.primary_key and inline_primary_key):
        parts.append('NOT NULL')
    if column.unique and not column.primary_key:
        parts.append('UNIQUE')
    if not column.autoincrement and not serial_type:
        default = _default_clause(column, dialect)
        if default:
            parts.append(default)
    if column.foreign_key is not None:
        fk = column.foreign_key
        parts.append(f"REFERENCES {quote(fk.ref_table, dialect)}({quote(fk.ref_column, dialect)})")
    return ' '.join(parts)


def render_create_table(table: Table, dialect: str, name: Optional[str] = None) -> str:
    composite = len(table.primary_key) > 1
    lines = [render_column(column, dialect, inline_primary_key=not composite) for column in table.columns]
    if composite:
        lines.append(f"PRIMARY KEY ({_columns(table.primary_key, dialect)})")
    body = ',\n    '.join(lines)
    return f"CREATE TABLE {quote(name or table.name, dialect)} (\n    {body}\n);"


def render_create_index(index: Index, dialect: str) -> str:
    unique = 'UNIQUE ' if index.unique else ''
    return (f"CREATE {unique}INDEX {quote(index.name, dialect)} "
            f"ON {quote(index.table, dialect)} ({_columns(index.columns, dialect)});")


def render_add_column(table: str, column: Column, dialect: str) -> str:
    keyword = 'ADD' if dialect == 'mssql' else 'ADD COLUMN'
    return f"ALTER TABLE {quote(table, dialect)} {keyword} {render_column(column, dialect)};"


def _drop_index(name: str, table: str, dialect: str) -> str:
    if dialect == 'mssql':
        return f"DROP INDEX {quote(name, dialect)} ON {quote(table, dialect)};"
    schema = table.rpartition('.')[0]
    qualified = f"{schema}.{name}" if dialect == 'postgresql' and schema else name
    return f"DROP INDEX {quote(qualified, dialect)};"


def _drop_constraint(table: str, name: str, dialect: str) -> str:
    return f"ALTER TABLE {quote(table, dialect)} DROP CONSTRAINT {quote(name, dialect)};"


def _rename_column(table: str, old: str, new: str, dialect: str) -> str:
    if dialect == 'mssql':
        return f"EXEC sp_rename '{_bare(table)}.{old}', '{new}', 'COLUMN';"
    return f"ALTER TABLE {quote(table, dialect)} RENAME COLUMN {quote(old, dialect)} TO {quote(new, dialect)};"


# === raw_sql tracking ===

def raw_sql_hash(text: str) -> str:
    normalized = '\n'.join(line.rstrip() for line in text.strip().splitlines())
    return hashlib.sha256(normalized.encode('utf-8')).hexdigest()[:16]


def read_raw_sql_state(migrations_path: Optional[str]) -> Dict[str, Optional[str]]:
    """
    Latest recorded hash of each raw_sql block, from markers in the migration files.

    Returns:
        name -> hash, or None if the last marker recorded the block's removal
    """
    state = {}
    if not migrations_path or not os.path.isdir(migrations_path):
        return state
    for path in sorted(glob.glob(os.path.join(migrations_path, '*.sql'))):
        with open(path, 'r', encoding='utf-8') as f:
            for name, digest, removed in _RAW_MARKER.findall(f.read()):
                state[name] = None if removed else digest
    return state


@dataclass
class RawChange:
    name: str
    status: str                     # 'new', 'changed', or 'removed'
    block: Optional[RawSQL] = None


def raw_sql_changes(definition: SchemaDefinition, migrations_path: Optional[str]) -> List[RawChange]:
    """raw_sql blocks that are new, changed, or removed since the last generated migration."""
    state = read_raw_sql_state(migrations_path)
    changes = []
    for name, block in definition.raw_sql.items():
        recorded = state.get(name)
        if recorded is None:
            changes.append(RawChange(name, 'new', block))
        elif recorded != raw_sql_hash(block.sql):
            changes.append(RawChange(name, 'changed', block))
    for name, recorded in state.items():
        if recorded is not None and name not in definition.raw_sql:
            changes.append(RawChange(name, 'removed'))
    return changes


# === Migration ===

@dataclass
class GeneratedMigration:
    sql: str
    live: int = 0                   # statements that will run
    review: int = 0                 # changes written commented-out
    tables: List[str] = field(default_factory=list)


class _Writer:
    def __init__(self):
        self.sections: List[str] = []
        self.live = 0
        self.review = 0

    def live_sql(self, heading: str, sql: str):
        self.sections.append(f"-- {heading}\n{sql}")
        self.live += 1

    def review_sql(self, heading: str, sql_lines: List[str], notes: List[str] = (), count: int = 1):
        lines = [f"-- REVIEW: {heading}"]
        lines += [f"-- {note}" for note in notes]
        for sql in sql_lines:
            lines += [f"-- {line}" if line else "--" for line in sql.splitlines()]
        self.sections.append('\n'.join(lines))
        self.review += count


def generate_migration(definition: SchemaDefinition, diff: SchemaDiff, live: Dict[str, LiveTable],
                       dialect: str, connection_name: str, schema_file: str,
                       raw_changes: List[RawChange] = ()) -> GeneratedMigration:
    """
    Render a diff (plus raw_sql changes) as the text of a .sql migration.

    Args:
        definition: The loaded schema file
        diff: diff_schema() output for it
        live: read_live_schema() output the diff was computed from
        dialect: The connection's database type
        connection_name: For the header
        schema_file: Path shown in the header
        raw_changes: raw_sql_changes() output
    """
    writer = _Writer()
    changes = diff.changes

    # --- Live, additive changes ---
    for change in _ordered_creates([c for c in changes if c.kind == 'create_table']):
        writer.live_sql(f"{change.table}: create table", render_create_table(change.declared, dialect))
    for change in changes:
        if not change.additive or change.kind == 'create_table':
            continue
        heading = f"{change.table}{'.' + change.column if change.column else ''}: {change.description}"
        writer.live_sql(heading, _render_additive(change, dialect))

    for raw in raw_changes:
        if raw.status == 'removed':
            continue
        marker = f"raw_sql: {raw.name} sha256:{raw_sql_hash(raw.block.sql)}"
        text = raw.block.sql if raw.block.sql.rstrip().endswith(';') else raw.block.sql.rstrip() + ';'
        if raw.status == 'changed':
            writer.sections.append(
                f"-- {marker}\n-- REVIEW: raw_sql block {raw.name!r} changed since it was last generated.\n"
                f"-- It runs as written below. IF NOT EXISTS won't update an object that already exists,\n"
                f"-- so drop the old one first here (or use CREATE OR REPLACE) if it should change.\n{text}"
            )
        else:
            writer.sections.append(f"-- {marker}\n{text}")
        writer.live += 1

    # --- Changes that need review, written commented-out ---
    review_by_table: Dict[str, List[Change]] = {}
    for change in changes:
        if not change.additive:
            review_by_table.setdefault(change.table, []).append(change)
    for table_name, table_changes in review_by_table.items():
        additive_columns = [c for c in changes if c.additive and c.kind == 'add_column' and c.table == table_name]
        _render_review(writer, definition, live, table_name, table_changes, dialect, additive_columns)

    for raw in raw_changes:
        if raw.status == 'removed':
            writer.sections.append(
                f"-- raw_sql: {raw.name} removed\n"
                f"-- REVIEW: raw_sql block {raw.name!r} was removed from the schema file. Whatever it\n"
                f"-- created is still in the database; drop it here if it should go."
            )
            writer.review += 1

    header = [
        f"-- Generated by `scribe schema generate` on {datetime.date.today().isoformat()}",
        f"-- for the '{connection_name}' connection ({dialect}) from {schema_file}.",
        f"-- {writer.live} statement(s) will run; {writer.review} change(s) need review and are commented out.",
    ]
    if writer.review:
        header.append("-- Uncomment and adjust the REVIEW sections you want to apply before running this.")

    tables = diff.changed_tables()
    return GeneratedMigration(
        sql='\n'.join(header) + '\n\n' + '\n\n'.join(writer.sections) + '\n',
        live=writer.live, review=writer.review, tables=tables,
    )


def _ordered_creates(creates: List[Change]) -> List[Change]:
    """New tables ordered so referenced tables are created first."""
    pending = {c.table.lower(): c for c in creates}
    ordered = []
    while pending:
        progressed = False
        for key, change in list(pending.items()):
            refs = {col.foreign_key.ref_table.lower() for col in change.declared.columns if col.foreign_key}
            if not (refs & (set(pending) - {key})):
                ordered.append(pending.pop(key))
                progressed = True
        if not progressed:  # circular references: keep declaration order
            ordered.extend(pending.values())
            break
    return ordered


def _render_additive(change: Change, dialect: str) -> str:
    table = change.table
    if change.kind == 'add_column':
        return render_add_column(table, change.declared, dialect)
    if change.kind == 'add_index':
        return render_create_index(change.declared, dialect)
    if change.kind == 'add_unique':
        name = f"uq_{_bare(table)}_{change.column}"
        column = quote(change.column, dialect)
        # MSSQL unique indexes treat NULLs as equal; filter them out to match SQLite/PostgreSQL
        where = f" WHERE {column} IS NOT NULL" if dialect == 'mssql' and change.declared.nullable else ""
        return f"CREATE UNIQUE INDEX {quote(name, dialect)} ON {quote(table, dialect)} ({column}){where};"
    if change.kind == 'add_foreign_key':
        fk = change.declared.foreign_key
        name = f"fk_{_bare(table)}_{change.column}"
        return (f"ALTER TABLE {quote(table, dialect)} ADD CONSTRAINT {quote(name, dialect)} "
                f"FOREIGN KEY ({quote(change.column, dialect)}) "
                f"REFERENCES {quote(fk.ref_table, dialect)}({quote(fk.ref_column, dialect)});")
    raise ValueError(f"No additive SQL for {change.kind}")


def _needs_rebuild(change: Change, dialect: str) -> bool:
    if dialect != 'sqlite':
        return False
    if change.kind in _SQLITE_REBUILD_KINDS:
        return True
    if change.kind == 'drop_unique' and change.live.origin == 'unique':
        return True  # constraint-backed autoindexes can't be dropped
    if change.kind == 'add_column' and not change.rename:
        return True  # UNIQUE / non-constant default / primary key
    return False


def _render_review(writer: _Writer, definition: SchemaDefinition, live: Dict[str, LiveTable],
                   table_name: str, changes: List[Change], dialect: str, additive_columns: List[Change]):
    if any(_needs_rebuild(c, dialect) for c in changes):
        _render_sqlite_rebuild(writer, definition, live[table_name.lower()], table_name, changes, additive_columns)
        return

    handled_renames = set()
    for change in changes:
        target = f"{table_name}{'.' + change.column if change.column else ''}"
        if change.rename:
            if change.rename in handled_renames:
                continue
            handled_renames.add(change.rename)
            old, new = change.rename
            added = next(c for c in changes if c.kind == 'add_column' and c.rename == change.rename)
            writer.review_sql(
                f"{table_name}: {old} → {new} looks like a renamed column.",
                [_rename_column(table_name, old, new, dialect)],
                notes=[f"If it is a rename, uncomment this one statement (adding and dropping instead "
                       f"would lose the data in {old}):"],
                count=2,
            )
            writer.sections[-1] += '\n'.join([
                '', '--', "-- If it isn't a rename, uncomment these two instead:",
                f"-- {render_add_column(table_name, added.declared, dialect)}",
                f"-- ALTER TABLE {quote(table_name, dialect)} DROP COLUMN {quote(old, dialect)};",
            ])
            continue

        sql, notes = _review_statement(change, table_name, live, dialect)
        heading = f"{target}: {change.description}"
        if change.destructive:
            heading = f"destructive — {heading}"
        writer.review_sql(heading, sql, notes)


def _review_statement(change: Change, table: str, live: Dict[str, LiveTable], dialect: str):
    """(SQL lines, notes) for a change that needs review, on PostgreSQL/MSSQL or a SQLite in-place change."""
    t = quote(table, dialect)
    column = change.declared if isinstance(change.declared, Column) else None
    c = quote(change.column, dialect) if change.column else None

    if change.kind == 'add_column':
        return [render_add_column(table, column, dialect)], [
            "Give it a default, or add it as nullable, backfill, and then make it NOT NULL."
        ]
    if change.kind == 'drop_column':
        notes = ["Dropping the column deletes its data."]
        if dialect == 'mssql':
            notes.append("Drop any default constraint on it first (see sys.default_constraints).")
        if dialect == 'sqlite':
            notes.append("SQLite can't drop a column that is indexed, UNIQUE, or part of a key.")
        return [f"ALTER TABLE {t} DROP COLUMN {c};"], notes
    if change.kind == 'alter_column_type':
        if dialect == 'postgresql':
            return [f"ALTER TABLE {t} ALTER COLUMN {c} TYPE {column.type};"], [
                f"Add USING {change.column}::{column.type} if the existing values need converting."
            ]
        null = 'NULL' if column.nullable else 'NOT NULL'
        return [f"ALTER TABLE {t} ALTER COLUMN {c} {column.type} {null};"], []
    if change.kind == 'alter_column_nullable':
        if dialect == 'postgresql':
            action = 'DROP NOT NULL' if column.nullable else 'SET NOT NULL'
            return [f"ALTER TABLE {t} ALTER COLUMN {c} {action};"], []
        null = 'NULL' if column.nullable else 'NOT NULL'
        return [f"ALTER TABLE {t} ALTER COLUMN {c} {column.type} {null};"], (
            [] if column.nullable else ["Update existing NULL values first."]
        )
    if change.kind == 'alter_column_default':
        default = declared_default_sql(column.default, dialect)
        if dialect == 'postgresql':
            action = f"SET DEFAULT {default}" if default is not None else "DROP DEFAULT"
            return [f"ALTER TABLE {t} ALTER COLUMN {c} {action};"], []
        sql = [f"ALTER TABLE {t} ADD DEFAULT {default} FOR {c};"] if default is not None else []
        return sql, ["Drop the existing default constraint first (see sys.default_constraints)."]
    if change.kind == 'alter_column_autoincrement':
        if dialect == 'postgresql':
            if column.autoincrement:
                return [f"ALTER TABLE {t} ALTER COLUMN {c} ADD GENERATED BY DEFAULT AS IDENTITY;"], []
            return [f"ALTER TABLE {t} ALTER COLUMN {c} DROP IDENTITY IF EXISTS;",
                    f"ALTER TABLE {t} ALTER COLUMN {c} DROP DEFAULT;"], ["Use whichever applies (identity or serial)."]
        return [], ["MSSQL can't add or remove IDENTITY on an existing column; the table has to be rebuilt."]
    if change.kind == 'alter_primary_key':
        live_pk = next((i for i in live[table.lower()].indexes if i.origin == 'primary_key'), None)
        sql = []
        if live_pk is not None:
            sql.append(_drop_constraint(table, live_pk.name, dialect))
        if change.declared:
            sql.append(f"ALTER TABLE {t} ADD PRIMARY KEY ({_columns(change.declared, dialect)});")
        return sql, []
    if change.kind in ('drop_index', 'drop_unique'):
        index = change.live
        if index.origin == 'unique':
            return [_drop_constraint(table, index.name, dialect)], []
        return [_drop_index(index.name, table, dialect)], []
    if change.kind == 'alter_index':
        return [_drop_index(change.live.name, table, dialect), render_create_index(change.declared, dialect)], []
    if change.kind == 'add_foreign_key':
        return [_render_additive(change, dialect)], ["Existing rows must satisfy the constraint."]
    if change.kind == 'drop_foreign_key':
        fk = change.live
        if fk.name:
            return [_drop_constraint(table, fk.name, dialect)], []
        return [], ["The foreign key has no name to drop it by."]
    return [], [f"No SQL is generated for {change.kind}."]


def _render_sqlite_rebuild(writer: _Writer, definition: SchemaDefinition, live_table: LiveTable,
                           table_name: str, changes: List[Change], additive_columns: List[Change]):
    table = definition.tables[table_name.lower()]
    temp = f"{_bare(table.name)}__scribe_new"
    # Columns that exist by the time this runs: live ones plus those the live statements above add
    existing = {c.name.lower() for c in live_table.columns}
    existing |= {c.column.lower() for c in additive_columns}
    copied = [c.name for c in table.columns if c.name.lower() in existing]
    # A likely rename copies the old column into the new one
    sources = list(copied)
    targets = list(copied)
    for change in changes:
        if change.kind == 'add_column' and change.rename:
            targets.append(change.rename[1])
            sources.append(change.rename[0])

    notes = [f"  {change.column + ': ' if change.column else ''}{change.description}" for change in changes]
    notes += [
        "To apply these, uncomment the rebuild below, including the foreign_keys line if other",
        "tables reference this one. Scribe turns enforcement off before the migration's transaction,",
        "checks every foreign key before committing, and turns enforcement back on afterwards.",
    ]
    sql = [
        "PRAGMA foreign_keys = OFF;",
        render_create_table(table, 'sqlite', name=temp),
        f"INSERT INTO {quote(temp, 'sqlite')} ({_columns(targets, 'sqlite')}) "
        f"SELECT {_columns(sources, 'sqlite')} FROM {quote(table.name, 'sqlite')};",
        f"DROP TABLE {quote(table.name, 'sqlite')};",
        f"ALTER TABLE {quote(temp, 'sqlite')} RENAME TO {quote(_bare(table.name), 'sqlite')};",
    ]
    sql += [render_create_index(index, 'sqlite') for index in definition.indexes_for(table.name)]
    writer.review_sql(f"SQLite can't make these changes to {table_name} in place:", sql, notes, count=len(changes))
