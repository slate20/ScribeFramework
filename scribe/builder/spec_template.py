"""
Generates the per-project PyInstaller spec file for a staged
`_scribe_build/` directory.
"""

from scribe.builder.db_config import DB_DRIVER_MODULES, configured_db_types

BASE_HIDDEN_IMPORTS = [
    'scribe.app',
    'scribe.parser',
    'scribe.parser.ast_nodes',
    'scribe.execution',
    'scribe.execution.context',
    'scribe.execution.builtins',
    'scribe.database',
    'scribe.database.sqlite',
    'scribe.database.manager',
    'scribe.database.query_builder',
    'scribe.helpers',
    'scribe.helpers.auth',
    'scribe.helpers.forms',
    'scribe.helpers.response',
    'scribe.loader',
    'scribe.migrations',
    'flask',
    'flask_wtf',
    'wtforms',
    'jinja2',
    'werkzeug',
    'waitress',
]

# scribe's own DB adapter module for each driver, gated the same way as the
# driver package itself: only bundled (and only required in the target
# venv, see preflight.py) when a project's scribe.json actually configures
# that database type.
DB_SCRIBE_MODULES = {
    'postgresql': 'scribe.database.postgresql',
    'mssql': 'scribe.database.mssql',
    'mysql': 'scribe.database.mysql',
}

SPEC_TEMPLATE = '''\
# -*- mode: python ; coding: utf-8 -*-
# Auto-generated by scribe-build. Do not edit directly.

a = Analysis(
    ['__main__.py'],
    pathex=[],
    binaries=[],
    datas=[('app_data', 'app_data')],
    hiddenimports={hiddenimports!r},
    hookspath=[],
    hooksconfig={{}},
    runtime_hooks=[],
    excludes=[
        'matplotlib',
        'numpy',
        'pandas',
        'scipy',
        'tkinter',
        'PyQt5',
        'PySide2',
    ],
    noarchive=False,
)

pyz = PYZ(a.pure, a.zipped_data)

exe = EXE(
    pyz,
    a.scripts,
    a.binaries,
    a.zipfiles,
    a.datas,
    [],
    name={name!r},
    debug=False,
    bootloader_ignore_signals=False,
    strip=False,
    upx=True,
    upx_exclude=[],
    runtime_tmpdir=None,
    console=True,
)
'''


def generate_spec(app_name: str, app_config: dict, extra_hiddenimports=None) -> str:
    hiddenimports = list(BASE_HIDDEN_IMPORTS)

    for db_type in configured_db_types(app_config):
        driver = DB_DRIVER_MODULES.get(db_type)
        if driver:
            hiddenimports.append(driver[0])
        scribe_module = DB_SCRIBE_MODULES.get(db_type)
        if scribe_module:
            hiddenimports.append(scribe_module)

    # Modules imported directly inside route Python blocks or lib/*.py
    # (see scribe.builder.import_scan) — PyInstaller can't see these on its
    # own because that code is shipped as precompiled bytecode data, not
    # source it analyzes.
    if extra_hiddenimports:
        for name in sorted(extra_hiddenimports):
            if name not in hiddenimports:
                hiddenimports.append(name)

    return SPEC_TEMPLATE.format(name=app_name, hiddenimports=hiddenimports)
